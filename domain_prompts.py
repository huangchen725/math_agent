def get_domain_prompt(domain: str) -> str:
    """根据领域名获取专属 prompt，未匹配则返回通用 prompt。"""
    if not domain:
        return _COMMON_PREFIX + """【领域策略：通用】
请根据题目特点选择合适的数学方法求解。
遇到计算时调用工具验证。"""
    # 精确匹配
    if domain in DOMAIN_PROMPTS:
        return DOMAIN_PROMPTS[domain]
    # 别名匹配
    domain_lower = domain.lower().strip()
    for alias, key in DOMAIN_ALIASES.items():
        if alias.lower() == domain_lower:
            return DOMAIN_PROMPTS[key]
    # 模糊匹配：包含关键词
    for alias, key in DOMAIN_ALIASES.items():
        if alias in domain or domain in alias:
            return DOMAIN_PROMPTS[key]
    # 兜底
    return _COMMON_PREFIX + """【领域策略：通用】
请根据题目特点选择合适的数学方法求解。
遇到计算时调用工具验证。"""
