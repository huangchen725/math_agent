def detect_domain(problem: str) -> str:
    normalized_problem = problem.casefold()
    scores = {
        domain: sum(1 for keyword in keywords if keyword.casefold() in normalized_problem)
        for domain, keywords in DOMAIN_KEYWORDS.items()
    }
    scores = {domain: score for domain, score in scores.items() if score > 0}
    return max(scores, key=scores.get) if scores else ""
